#!/usr/bin/env python3
"""Rebuild the library index from the notes.

Usage: build_index.py
Reads front matter of notes/*/*.md and writes:
  data/library.json               machine index (the web app reads this)
  library/README.md               every link, newest first
  library/by-usefulness/<u>.md    helpful / mixed / misleading / noise
  library/by-topic/<topic>.md     one file per topic
All files under library/ and data/ are generated: edit the notes, then rerun this.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
USEFULNESS = ["helpful", "mixed", "misleading", "noise"]
BLURB = {
    "helpful": "Verified, actionable tools, hacks or facts.",
    "mixed": "A real tool or fact, but with misleading framing or unproven claims.",
    "misleading": "Mostly hoax, hype or unsupported claims.",
    "noise": "Nothing informative (side quests).",
}
REQUIRED = ["url", "platform", "title", "usefulness", "verdict", "key_info"]


def read_note(path):
    text = path.read_text(encoding="utf8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        sys.exit(f"{path}: missing front matter")
    meta = yaml.safe_load(m.group(1)) or {}
    missing = [k for k in REQUIRED if not meta.get(k)]
    if missing:
        sys.exit(f"{path}: front matter lacks {', '.join(missing)}")
    if meta["usefulness"] not in USEFULNESS:
        sys.exit(f"{path}: usefulness must be one of {USEFULNESS}")
    return meta


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def row(i):
    t = i["title"].replace("|", "/")
    k = i["key_info"].replace("|", "/").replace("\n", " ")
    return f"| [{t}]({i['url']}) | {i['author']} | {i['usefulness']} | {i['verdict']} | {k} | [note](../{i['note_path']}) |"


def table(items, up="."):
    head = "| Link | Author | Usefulness | Verdict | Key info | Note |\n|---|---|---|---|---|---|\n"
    return head + "\n".join(row(i).replace("](../", f"]({up}/") for i in items) + "\n"


def main():
    items = []
    for p in sorted((ROOT / "notes").glob("*/*.md")):
        meta = read_note(p)
        stamp = str(meta.get("posted") or "")
        items.append({
            "id": p.stem,
            "platform": meta["platform"],
            "url": meta["url"],
            "title": meta["title"],
            "author": meta.get("author") or "",
            "posted": stamp,
            "type": meta.get("type") or "",
            "topics": [slug(t) for t in meta.get("topics") or []],
            "tools": meta.get("tools") or [],
            "usefulness": meta["usefulness"],
            "verdict": meta["verdict"],
            "key_info": " ".join(str(meta["key_info"]).split()),
            "note_path": str(p.relative_to(ROOT)),
        })
    items.sort(key=lambda i: i["posted"], reverse=True)

    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "library.json").write_text(json.dumps(items, indent=2, ensure_ascii=False) + "\n")

    lib = ROOT / "library"
    for sub in ("by-usefulness", "by-topic"):
        d = lib / sub
        d.mkdir(parents=True, exist_ok=True)
        for f in d.glob("*.md"):
            f.unlink()
    note = "_Generated by `scripts/build_index.py`. Edit the notes, not this file._\n\n"

    counts = {u: sum(1 for i in items if i["usefulness"] == u) for u in USEFULNESS}
    summary = " · ".join(f"{u}: {n}" for u, n in counts.items())
    (lib / "README.md").write_text(f"# Library\n\n{note}{len(items)} links. {summary}\n\n" + table(items))

    for u in USEFULNESS:
        sel = [i for i in items if i["usefulness"] == u]
        body = f"# {u.capitalize()}\n\n{note}{BLURB[u]}\n\n" + (table(sel, "../..") if sel else "_None yet._\n")
        (lib / "by-usefulness" / f"{u}.md").write_text(body)

    topics = defaultdict(list)
    for i in items:
        for t in i["topics"] or ["untagged"]:
            topics[t].append(i)
    for t, sel in sorted(topics.items()):
        (lib / "by-topic" / f"{t}.md").write_text(f"# Topic: {t}\n\n{note}{len(sel)} links.\n\n" + table(sel, "../.."))
    print(f"{len(items)} notes, {len(topics)} topics, usefulness: {summary}")


if __name__ == "__main__":
    main()
